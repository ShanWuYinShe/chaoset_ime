// ToTraditional 把文本中的简体字转换为繁体字。映射表未收录的字符
// （含一对多歧义字）原样保留——零错误策略见 s2t 注释。
func ToTraditional(s string) string {
	if !strings.ContainsFunc(s, func(r rune) bool { _, ok := s2t[r]; return ok }) {
		return s
	}
	var b strings.Builder
	b.Grow(len(s))
	for _, r := range s {
		if t, ok := s2t[r]; ok {
			b.WriteRune(t)
		} else {
			b.WriteRune(r)
		}
	}
	return b.String()
}
